CAPTURE = json.loads((Path(__file__).parent / "fixtures/localization_2026_09_28.json").read_text())


def test_real_capture_keeps_negative_routing_evidence():
    rows = CAPTURE["observed_stt"]
    cyrillic = [r for r in rows if not re.search(r"[A-Za-z]", r["text"])]
    mixed = [r for r in rows if re.search(r"[A-Za-z]", r["text"])]
    assert len(rows) == 22 and len(cyrillic) == 13 and len(mixed) == 9
    assert not any(r["matched_continue"] for r in cyrillic)
    assert all(r["matched_continue"] for r in mixed)
    assert CAPTURE["snapshot_lines"] == 2792


@pytest.mark.parametrize("original,wire", [
    ("Сенің атың кім?", "What is your name?"),
    ("What's your name?", "What's your name?"),
    ("Привет.", "Hello."),
    ("Жемістер туралы сөйлесейік.", "Let's talk about fruit."),
])
async def test_captured_input_with_synthetic_router_acceptance(original, wire, fake_openai, captured_publish, monkeypatch):
    row = next(r for r in CAPTURE["observed_stt"] if r["text"] == original)
    monkeypatch.setattr(settings, "STT_ENGLISH_BRIDGE_ENABLED", True)
    monkeypatch.setattr(settings, "DEFAULT_TTS_LANGUAGE", "kk")
    await device_state.set_cloud_tts(True)
    fake_openai.audio.transcriptions._text = original
    fake_openai.chat.completions.translations[original] = wire
    fake_openai.chat.completions._reply = "Менің атым Мокси. Саған қандай жеміс ұнайды?"
    stt_request.note_conversation_active(TEST_DEVICE_ID)
    await stt_request.handle_stt_request(TEST_DEVICE_ID, _request(row["uuid"], 3, audio=b"\x00\x01" * (row["audio_bytes"] // 2)))
    prefix = zmqSTTResponse.DESCRIPTOR.full_name.encode() + b":"
    final = zmqSTTResponse.FromString(captured_publish[0][1][len(prefix):])
    assert (final.uuid, final.speech, final.error_code) == (row["uuid"], wire, 0)
    captured_publish.clear()
    # This real-request-shaped event is generated by this test, not observed
    # post-fix firmware behavior. Hardware must still supply it independently.
    await RemoteChatBrain().handle_router_request(TEST_DEVICE_ID, request(final.uuid, final.speech))
    chat_call = next(c for c in fake_openai.chat.completions.calls if not c["messages"][0]["content"].startswith("Translate"))
    assert chat_call["messages"][-1]["content"] == original
    chats, audio = _split(captured_publish)
    assert chats[0]["input_speech"] == wire
    assert len(audio) == 1 and audio[0].event_id == row["uuid"] and any(audio[0].audio.buffer)


async def test_logged_xix_answer_survives_and_is_shortened(fake_openai, captured_publish):
    reply = CAPTURE["rejected_kazakh_answer"]
    assert "XIX" in reply and matches_output_language(reply, "kk")
    fake_openai.chat.completions._reply = reply
    await device_state.set_cloud_tts(True)
    await RemoteChatBrain().handle_router_request(TEST_DEVICE_ID, request("cars", "Tell me about cars"))
    chats, audio = _split(captured_publish)
    output = chats[0]["output"]["text"]
    assert "XIX" in output and "естімедім" not in output
    assert len(output.split()) <= 35
    assert len(fake_openai.chat.completions.calls) == 1
    assert audio[0].event_id == "cars"


async def test_exact_logged_prompt_echo_never_reaches_brain(fake_openai, captured_publish):
    row = next(r for r in CAPTURE["observed_stt"] if "Preserve the spoken language" in r["text"])
    fake_openai.audio.transcriptions._text = row["text"]
    stt_request.note_conversation_active(TEST_DEVICE_ID)
    await stt_request.handle_stt_request(TEST_DEVICE_ID, _request(row["uuid"], 3, audio=b"\x00\x01" * (row["audio_bytes"] // 2)))
    prefix = zmqSTTResponse.DESCRIPTOR.full_name.encode() + b":"
    final = zmqSTTResponse.FromString(captured_publish[0][1][len(prefix):])
    assert final.error_code == 66 and final.speech == ""
    assert fake_openai.chat.completions.calls == fake_openai.audio.speech.calls == []
